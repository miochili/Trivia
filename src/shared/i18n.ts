const DICTS: Record<Locale, Dict> = { en, es, de };

/** Translate a key. Missing params render as-is; `cat` params are category ids. */
export function translate(locale: Locale, key: string, params: Params = {}): string {
  const dict = DICTS[locale] ?? en;
  const template = (dict as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => {
    const v = params[name];
    if (v === undefined) return `{${name}}`;
    if (name === "cat") return (dict as Record<string, string>)[`cat.${v}`] ?? String(v);
    return String(v);
  });
}

export const categoryName = (locale: Locale, c: CategoryId) => translate(locale, `cat.${c}`);
export const difficultyName = (locale: Locale, d: Difficulty) => translate(locale, `diff.${d}`);
export const specialName = (locale: Locale, s: SpecialTileType) => translate(locale, `special.${s}`);

export function detectLocale(langs: readonly string[] = []): Locale {
  for (const l of langs) {
    const base = l.toLowerCase().split("-")[0] as Locale;
    if ((LOCALES as readonly string[]).includes(base)) return base;
  }
  return DEFAULT_LOCALE;
}
